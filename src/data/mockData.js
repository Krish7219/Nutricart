export const trendingMeals = meals.filter(meal => meal.trending);

export const getMealById = (id) => meals.find(meal => meal.id === id);

export const getVendorById = (id) => vendors.find(vendor => vendor.id === id);

export const getMealsByVendor = (vendorId) => meals.filter(meal => meal.vendorId === vendorId);

export const getMealsByGoal = (goal) => meals.filter(meal => meal.goals.includes(goal));

export const getMealsByDietary = (dietary) => meals.filter(meal => meal.dietary.includes(dietary));

export const getRecommendations = (userId) => {
  const user = users.find(u => u.id === userId);
  if (!user) return meals.slice(0, 4);
  
  // Recommend based on user's goals and dietary preferences
  return meals.filter(meal => 
    meal.goals.some(goal => user.goals.includes(goal)) ||
    meal.dietary.some(diet => user.dietaryPreferences.includes(diet))
  ).slice(0, 4);
};

export const getRepeatOrders = (userId) => {
  const user = users.find(u => u.id === userId);
  if (!user) return [];
  
  return user.orderHistory.map(orderId => getMealById(orderId)).filter(Boolean);
};
